    public static string Get(string key, string language) =>
        Labels.TryGetValue(key, out var text)
            ? language switch { "nn" => text.Nn, "en" => text.En, _ => text.Nb }
            : throw new KeyNotFoundException("Report label missing: " + key);

    public static bool Has(string key) => Labels.ContainsKey(key);

    public static IEnumerable<string> Keys => Labels.Keys;
