"""Generate src/Sikkerheit.Contracts/Catalog.g.cs from development-package/scripts/contract_catalog.py.

The package catalog is the single source of closed sets (checks, Problem.code with HTTP status, reason codes,
event table, roles, Graph modules). Run after changing the package catalog; CI checks that the file is current:

    python3 -I tools/contracts/gen_csharp_catalog.py --check
"""
import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'src' / 'Sikkerheit.Contracts' / 'Catalog.g.cs'


def load_catalog():
    path = ROOT / 'development-package' / 'scripts' / 'contract_catalog.py'
    spec = importlib.util.spec_from_file_location('contract_catalog', path)
    module = importlib.util.module_from_spec(spec)
    sys.dont_write_bytecode = True
    spec.loader.exec_module(module)
    return module


def pascal(value):
    parts = value.replace('-', '_').replace('.', '_').split('_')
    return ''.join(p[:1].upper() + p[1:] for p in parts if p)


def string_list(name, values, indent='    '):
    items = ', '.join(f'"{v}"' for v in values)
    return f'{indent}public static readonly IReadOnlyList<string> {name} = [{items}];'


def render(c):
    lines = [
        '// <auto-generated>',
        '// Generated by tools/contracts/gen_csharp_catalog.py from development-package/scripts/contract_catalog.py.',
        '// Do not edit by hand.',
        '// </auto-generated>',
        '#nullable enable',
        'namespace Sikkerheit.Contracts;',
        '',
        '/// <summary>Closed catalogs of the Development Package; see 03 and 05.</summary>',
        'public static partial class Catalog',
        '{',
        f'    public const string Version = "{c.CATALOG_VERSION}";',
        '',
        '    public static readonly IReadOnlyList<CheckDefinition> Checks =',
        '    [',
    ]
    for cid, name, phase, mode, source, subject in c.CHECKS:
        lines.append(f'        new("{cid}", "{name}", "{phase}", "{mode}", "{source}", "{subject}"),')
    lines += ['    ];', '']
    lines.append(string_list('GraphPermissions', c.GRAPH_PERMISSIONS))
    lines.append(string_list('DeferredIds', c.DEFERRED_IDS))
    lines.append(f'    public const string DirectorySyncRole = "{c.DIRECTORY_SYNC_ROLE}";')
    lines.append(string_list('CaConditions', c.CA_CONDITIONS))
    lines.append(string_list('CaGrantControls', c.CA_GRANT_CONTROLS))
    lines.append(string_list('MethodKinds', c.METHOD_KINDS))
    lines.append(string_list('MfaMethodKinds', c.MFA_METHOD_KINDS))
    lines.append(string_list('GraphModules', c.GRAPH_MODULES))
    lines.append(string_list('CapabilityStatuses', c.CAPABILITY_STATUSES))
    lines.append(string_list('AgentCollectorReasons', c.AGENT_COLLECTOR_REASONS))
    lines.append(string_list('GraphCollectorReasons', c.GRAPH_COLLECTOR_REASONS))
    lines.append(string_list('ReasonCodes', c.REASON_CODES))
    lines.append(string_list('InformationalReasons', c.INFORMATIONAL_REASONS))
    lines.append(string_list('Results', c.RESULTS))
    lines.append(string_list('EventCauses', c.EVENT_CAUSES))
    lines.append(string_list('WorkflowStates', c.WORKFLOW_STATES))
    lines.append(string_list('Roles', c.ROLES))
    lines.append(string_list('Languages', c.LANGUAGES))
    lines.append(string_list('AuditReads', c.AUDIT_READS))
    lines.append(string_list('CrossOrganizationOperations', c.CROSS_ORG_OPERATIONS))
    lines.append(string_list('LifecycleActions', c.LIFECYCLE_ACTIONS))
    lines.append(string_list('RetentionPurgeOrder', c.RETENTION_PURGE_ORDER))
    lines.append(string_list('SecurityLogActions', c.SECURITY_LOG_ACTIONS))
    lines.append(string_list('AlwaysInformational', c.ALWAYS_INFORMATIONAL))
    lines.append(string_list('OsFamilies', c.OS_FAMILIES))
    lines.append(string_list('ReleaseKinds', c.RELEASE_KINDS))
    lines.append('')
    lines.append('    /// <summary>eventType → allowed causes and assessmentId rule (required, nullable, null).</summary>')
    lines.append('    public static readonly IReadOnlyDictionary<string, EventRule> EventTable = new Dictionary<string, EventRule>')
    lines.append('    {')
    for event, (causes, assessment) in c.EVENT_TABLE.items():
        joined = ', '.join(f'"{x}"' for x in causes)
        lines.append(f'        ["{event}"] = new([{joined}], "{assessment}"),')
    lines += ['    };', '']
    lines.append('    public static readonly IReadOnlyDictionary<string, ProblemDefinition> Problems = new Dictionary<string, ProblemDefinition>')
    lines.append('    {')
    for code, status, action in c.PROBLEM_CODES:
        lines.append(f'        ["{code}"] = new("{code}", {status}, "{action}"),')
    lines += ['    };', '}', '', '/// <summary>Problem.code values as constants.</summary>', 'public static class ProblemCodes', '{']
    for code, _, _ in c.PROBLEM_CODES:
        lines.append(f'    public const string {pascal(code)} = "{code}";')
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='fail if the generated file is not current')
    args = parser.parse_args()
    text = render(load_catalog())
    if args.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.exists() else ''
        if current != text:
            print(f'{TARGET.relative_to(ROOT)} is out of date; run tools/contracts/gen_csharp_catalog.py')
            return 1
        print('catalog is current')
        return 0
    TARGET.write_text(text, encoding='utf-8')
    print(f'wrote {TARGET.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
